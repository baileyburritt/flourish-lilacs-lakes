// A4: fails if any hex color literal appears in app source outside the
// generated token file (which does not exist until ticket C1 runs — until
// then, no hex literals are allowed anywhere in app/ source).
const fs = require('fs');
const path = require('path');

const APP_ROOT = path.resolve(__dirname, '..');
const TOKEN_FILE = path.join(APP_ROOT, 'theme', 'tokens.ts');

const SCAN_EXTENSIONS = new Set(['.ts', '.tsx', '.js', '.jsx']);
const IGNORE_DIRS = new Set([
  'node_modules',
  '.expo',
  'dist',
  'web-build',
  'ios',
  'android',
  'playwright-report',
  'test-results',
  'coverage',
  '.git',
]);

const HEX_LITERAL = /#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{4}|[0-9a-fA-F]{3})\b/g;

function walk(dir, files) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (IGNORE_DIRS.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full, files);
    } else if (SCAN_EXTENSIONS.has(path.extname(entry.name))) {
      files.push(full);
    }
  }
  return files;
}

const files = walk(APP_ROOT, []);
const violations = [];

for (const file of files) {
  if (file === TOKEN_FILE) continue;

  const content = fs.readFileSync(file, 'utf8');
  const lines = content.split('\n');

  lines.forEach((line, index) => {
    const matches = line.match(HEX_LITERAL);
    if (matches) {
      for (const match of matches) {
        violations.push({ file: path.relative(APP_ROOT, file), line: index + 1, match });
      }
    }
  });
}

if (violations.length > 0) {
  console.error('Token conformance check FAILED — hex literal(s) found outside the generated token file:');
  for (const v of violations) {
    console.error(`  ${v.file}:${v.line}  ${v.match}`);
  }
  console.error(
    `\nColors must come from ${path.relative(APP_ROOT, TOKEN_FILE)} (generated by ticket C1), not hand-written hex values.`
  );
  process.exit(1);
}

console.log(`Token conformance check passed — no stray hex literals in ${files.length} file(s) scanned.`);
